def translate(value: object, language: str = "en") -> str:
    """Translate an English UI phrase, preserving simple interpolated values."""
    text = str(value)
    if language != "pt":
        return _english(text)
    if text in PORTUGUESE:
        return PORTUGUESE[text]

    # Keep runtime values (HTTP status, file names and progress counts) intact.
    patterns = (
        (r"BitMidi is temporarily unavailable \(HTTP (\d+)\)\. Please try again shortly\.", lambda m: f"O BitMidi está temporariamente indisponível (HTTP {m[1]}). Tente novamente em instantes."),
        (r"BitMidi is returning HTTP 520 from its upstream server\. The catalog is temporarily unavailable; try again shortly\.", lambda _m: "O servidor do BitMidi respondeu com HTTP 520. O catálogo está temporariamente indisponível; tente novamente em instantes."),
        (r"BitMidi search failed \(([A-Za-z0-9_]+)\)\. Please try again later\.", lambda m: f"A pesquisa no BitMidi falhou ({m[1]}). Tente novamente mais tarde."),
        (r"Preparing cached MIDI Hub · (\d+)/(\d+) covers", lambda m: f"Preparando Catálogo MIDI em cache · {m[1]}/{m[2]} capas"),
        (r"Loading MIDI Hub covers · (\d+)/(\d+)", lambda m: f"Carregando capas do Catálogo MIDI · {m[1]}/{m[2]}"),
        (r"Using cached MIDI Hub data · (\d+)/(\d+)", lambda m: f"Usando dados do Catálogo MIDI em cache · {m[1]}/{m[2]}"),
        (r"MIDI Hub ready · (\d+)/(\d+) covers", lambda m: f"Catálogo MIDI pronto · {m[1]}/{m[2]} capas"),
        (r"Couldn't reach nanomidi\.net\. Check your connection and try again\. \(([A-Za-z0-9_]+)\)", lambda m: f"Não foi possível acessar nanomidi.net. Verifique sua conexão e tente novamente. ({m[1]})"),
        (r"Couldn't download this MIDI file\. (.+)", lambda m: f"Não foi possível baixar este arquivo MIDI. {m[1]}"),
        (r"Playing MIDI file: (.+)", lambda m: f"Tocando arquivo MIDI: {m[1]}"),
        (r"Playlist skipped missing MIDI: (.+)", lambda m: f"Playlist pulou MIDI ausente: {m[1]}"),
        (r"Playlist skipped unreadable MIDI: (.+)", lambda m: f"Playlist pulou MIDI ilegível: {m[1]}"),
        (r"Downloaded MIDI File: (.+)", lambda m: f"Arquivo MIDI baixado: {m[1]}"),
        (r"MIDI playback stopped: (.+)", lambda m: f"A reprodução do MIDI parou: {m[1]}"),
        (r"Finger limit \((\d+)\) reached, skipping (note|drum hit)", lambda m: f"Limite de dedos ({m[1]}) atingido; {'nota ignorada' if m[2] == 'note' else 'batida de bateria ignorada'}"),
        (r"out of range: (.+)", lambda m: f"fora do alcance: {m[1]}"),
        (r"no mapping: (.+)", lambda m: f"sem mapeamento: {m[1]}"),
        (r"skipped double: note (\d+) ch (\d+)", lambda m: f"nota duplicada ignorada: nota {m[1]}, canal {m[2]}"),
        (r"Speed: ([0-9.]+)%", lambda m: f"Velocidade: {m[1]}%"),
        (r"This keybind is already in use by (.+): (.+)", lambda m: f"Este atalho já está em uso por {m[1]}: {m[2]}"),
        (r"Could not open MIDI input: (.+)", lambda m: f"Não foi possível abrir a entrada MIDI: {m[1]}"),
        (r"(.+) set to (.+)", lambda m: f"{translate(m[1], 'pt')} definido para {m[2]}"),
    )
    for pattern, render in patterns:
        match = re.fullmatch(pattern, text)
        if match:
            return render(match)
    return text


